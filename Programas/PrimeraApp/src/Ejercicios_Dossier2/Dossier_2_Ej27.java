/*
Hacer un programa que muestre la tabla de multiplicar del número 5 usando
un bucle while
*/

public class Dossier_2_Ej27 {
    public static void main(String[] args) {
        int i = 1;
        System.out.println("Tabla del 5:");
        while(i<=10){
            System.out.println(i + " x 5 = " + i*5);
            i++;
        }
    }
}