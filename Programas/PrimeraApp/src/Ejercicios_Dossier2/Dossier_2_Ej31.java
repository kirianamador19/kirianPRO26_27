/*
Hacer un programa que muestre la tabla de multiplicar del número 5 usando
un bucle for
*/

public class Dossier_2_Ej31 {
    public static void main(String[] args) {
        System.out.println("Tabla del 5: ");
        int i;
        for(i = 1;i <= 10;i++){
            System.out.println("5 x " + i + " = " + i*5);
        }
    }
}